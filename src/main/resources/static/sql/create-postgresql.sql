-- =========================================================
-- TEAM ROLES
-- =========================================================

CREATE TABLE team_roles (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(50) NOT NULL,

    PRIMARY KEY (id),
    UNIQUE (name)
);


-- =========================================================
-- CIRCUITS
-- =========================================================

CREATE TABLE circuits (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(100) NOT NULL,
    country VARCHAR(100),
    length_meters BIGINT,
    description TEXT,
    image VARCHAR(255),
    active BOOLEAN NOT NULL DEFAULT TRUE,

    PRIMARY KEY (id),
    UNIQUE (name)
);


-- =========================================================
-- BIKES
-- =========================================================

CREATE TABLE bikes (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    brand VARCHAR(50) NOT NULL,
    model VARCHAR(50) NOT NULL,
    year INT NOT NULL,
    category VARCHAR(50) NOT NULL,
    description TEXT,
    bike_image VARCHAR(255),
    chassis_number VARCHAR(255) NOT NULL,
    current_km BIGINT NOT NULL DEFAULT 0,
    daily_price DECIMAL(10,2),
    status VARCHAR(255) NOT NULL DEFAULT 'AVAILABLE',

    PRIMARY KEY (id),
    UNIQUE (chassis_number)
);


-- =========================================================
-- SERVICES
-- =========================================================

CREATE TABLE services (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(100) NOT NULL,
    description TEXT NOT NULL,
    pricing_type VARCHAR(20) NOT NULL,
    base_price DECIMAL(10,2),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    PRIMARY KEY (id)
);


-- =========================================================
-- TEAM USERS / STAFF
-- =========================================================

CREATE TABLE team_users (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(50) NOT NULL,
    surname VARCHAR(50) NOT NULL,
    phone VARCHAR(20) NOT NULL,
    email VARCHAR(50) NOT NULL,
    birth_date DATE NOT NULL,
    bio TEXT,
    profile_image VARCHAR(255),
    instagram VARCHAR(255),
    created_at TIMESTAMP NOT NULL,
    team_role_id BIGINT NOT NULL,

    PRIMARY KEY (id),

    CONSTRAINT fk_team_users_roles
        FOREIGN KEY (team_role_id)
        REFERENCES team_roles(id)
);


-- =========================================================
-- EVENTS
-- =========================================================

CREATE TABLE events (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(150) NOT NULL,
    description TEXT,
    organizer VARCHAR(150),
    circuit_id BIGINT NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    max_participants INT,
    current_participants INT NOT NULL DEFAULT 0,
    status VARCHAR(30) NOT NULL,
    created_at TIMESTAMP NOT NULL,

    PRIMARY KEY (id),

    CONSTRAINT fk_events_circuits
        FOREIGN KEY (circuit_id)
        REFERENCES circuits(id)
);


-- =========================================================
-- EVENT SERVICE PRICES
-- =========================================================

CREATE TABLE event_service_prices (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    price_one_day DECIMAL(10,2),
    price_two_days DECIMAL(10,2),
    price_three_days DECIMAL(10,2),
    price_full_event DECIMAL(10,2),
    event_id BIGINT NOT NULL,
    service_id BIGINT NOT NULL,

    PRIMARY KEY (id),

    CONSTRAINT uq_event_service
        UNIQUE (event_id, service_id),

    CONSTRAINT fk_esp_event
        FOREIGN KEY (event_id)
        REFERENCES events(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_esp_service
        FOREIGN KEY (service_id)
        REFERENCES services(id)
        ON DELETE CASCADE
);


-- =========================================================
-- PENDING BOOKINGS
-- =========================================================
--
-- Utilizzata sia per:
-- CREATE = nuova prenotazione
-- UPDATE = modifica prenotazione esistente
--
-- booking_id Ã¨ NULL per una nuova prenotazione.
-- original_total_price Ã¨ NULL per una nuova prenotazione.
-- difference_amount Ã¨ NULL per una nuova prenotazione.
--

CREATE TABLE pending_bookings (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,

    user_keycloak_id VARCHAR(255) NOT NULL,

    booking_json TEXT NOT NULL,

    total_price DECIMAL(10,2),

    original_total_price DECIMAL(10,2),
    difference_amount DECIMAL(10,2),

    booking_id BIGINT,

    operation_type VARCHAR(30),

    stripe_session_id VARCHAR(255),
    payment_status VARCHAR(30),

    created_at TIMESTAMP NOT NULL,

    PRIMARY KEY (id)
);


-- =========================================================
-- BOOKINGS
-- =========================================================

CREATE TABLE bookings (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,

    user_keycloak_id VARCHAR(255) NOT NULL,

    status VARCHAR(30) NOT NULL,
    payment_status VARCHAR(30) NOT NULL,

    total_price DECIMAL(10,2),

    credit_amount DECIMAL(10,2) NOT NULL DEFAULT 0,

    created_at TIMESTAMP NOT NULL,
    cancellation_deadline DATE,

    event_id BIGINT NOT NULL,

    booking_start_date DATE NOT NULL,
    booking_end_date DATE NOT NULL,

    PRIMARY KEY (id),

    CONSTRAINT fk_booking_event
        FOREIGN KEY (event_id)
        REFERENCES events(id)
        ON DELETE CASCADE
);


-- =========================================================
-- BOOKING BIKE ALLOCATIONS
-- =========================================================

CREATE TABLE booking_bike_allocations (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,

    rental_start_date DATE NOT NULL,
    rental_end_date DATE NOT NULL,

    booking_id BIGINT NOT NULL,
    bike_id BIGINT NOT NULL,

    PRIMARY KEY (id),

    CONSTRAINT fk_bba_booking
        FOREIGN KEY (booking_id)
        REFERENCES bookings(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_bba_bike
        FOREIGN KEY (bike_id)
        REFERENCES bikes(id)
        ON DELETE CASCADE
);


-- =========================================================
-- BOOKING SERVICES
-- =========================================================

CREATE TABLE booking_services (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,

    service_start_date DATE NOT NULL,
    service_end_date DATE NOT NULL,
    days INT NOT NULL,

    price_at_booking DECIMAL(10,2) NOT NULL,

    service_id BIGINT NOT NULL,
    booking_id BIGINT NOT NULL,

    PRIMARY KEY (id),

    CONSTRAINT fk_bs_booking
        FOREIGN KEY (booking_id)
        REFERENCES bookings(id),

    CONSTRAINT fk_bs_service
        FOREIGN KEY (service_id)
        REFERENCES services(id)
);


